(* The eps_1 machine at tape level: the rung branch.

   Eps1Ladder.v fixes what the machine has to compute, as a rule about values.
   This file is the first tape-level piece under it: the part of the run that
   decides whether another rung is spent, and hands the copy a frame it can use.

   The machine (tools/eps1_machine.py, 57 states, 100 rows) is

       stage branch (eps_0's rounds, one block mark per round)
         -> rung branch (ENTRY, G1..G3: spend one budget mark, or halt)
           -> copy (WALK..: rebuild the block from the value, push the budget)
             -> back into a round

   and the frame is

       1^{a+1}(budget) 0^j [block: empty] 1(wall) 0^2 1^v 0 1(seed)

   with the head on the wall.  The rung branch is what this file proves about,
   for every value length v, every blank gap m between the wall and the budget's
   rightmost mark, and every budget length:

     * [rung_halts]: with one budget mark left, the walk finds nothing to spend,
       and the machine halts with the value region untouched -- value, blank and
       seed in the same cells.  That is the a = 0 rung, at tape level.
     * [rung_reaches_copy]: with at least two marks, it erases the rightmost,
       returns over the gap, and stops one cell right of the wall in [WALK] --
       the copy's entry -- with the block region blank (so the copy starts flush
       at wall-2, as its own entry expects) and the value region untouched.

   "Untouched" is not a slogan here: the value, blank and seed appear in the
   conclusion as the literal list [ones v ++ bl :: on :: []], and the proofs
   never take a transition in that region.  The rung branch is value-blind, and
   that is exactly why the same proof covers every v.

   The third piece here is the stage branch's *decision*: [S1] erases a block
   mark, [S2] asks whether another is left, and on a blank the machine hands
   over to [ENTRY] -- a rung is spent.  [block_spent_reaches_copy] composes
   that handover with the rung branch above, so from "the block is spent" the
   machine provably reaches the copy's entry with the copy's frame.  That is
   the recursion decision; it says nothing about what the block's rounds do.

   What is NOT here, and must not be read as done: the copy sweep (states
   33..55 pass over the value and rebuild the block, which is the rest of step 3
   in FGH_MACHINES_PLAN.md -- that is rocq/Eps1Copy.v, which ends in [sweep]),
   the *interior* of the eps_0 stage branch -- its rounds, one value mark per
   round, are still only simulated, and FGH_MACHINES_PLAN.md records the round
   statement they owe -- the handover back from the copy into a round, the
   blank-tape prologue, and any step count for a whole rung.  The table below is
   generated from tools/eps1_machine.py by tools/emit_eps1_tape.py, so the
   machine proved about here is the machine that runs there; `--check` compares
   them without writing. *)

