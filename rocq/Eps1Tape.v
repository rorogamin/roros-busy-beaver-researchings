(** ** Runs *)

Lemma run_cat : forall (k1 k2 : nat) (c1 c2 c3 : conf),
  run tbl k1 c1 = Some c2 ->
  run tbl k2 c2 = Some c3 ->
  run tbl (k1 + k2) c1 = Some c3.
Proof.
  intros k1 k2 c1 c2 c3 H1 H2.
  rewrite run_add, H1. cbn. exact H2.
Qed.

(** ** One-step facts for the rung branch *)

Lemma st_ENTRY_on : forall L R,
  step tbl (mkConf ENTRY L on R) = Some (mkConf G1 (tl L) (hd bl L) (on :: R)).
Proof. reflexivity. Qed.

Lemma st_G1_bl : forall L R,
  step tbl (mkConf G1 L bl R) = Some (mkConf G1 (tl L) (hd bl L) (bl :: R)).
Proof. reflexivity. Qed.

Lemma st_G1_on : forall L R,
  step tbl (mkConf G1 L on R) = Some (mkConf G2 (tl L) (hd bl L) (bl :: R)).
Proof. reflexivity. Qed.

Lemma st_G2_on : forall L R,
  step tbl (mkConf G2 L on R) = Some (mkConf G3 (on :: L) (hd bl R) (tl R)).
Proof. reflexivity. Qed.

Lemma st_G2_bl : forall L R,
  step tbl (mkConf G2 L bl R) = None.
Proof. reflexivity. Qed.

Lemma st_G3_bl : forall L R,
  step tbl (mkConf G3 L bl R) = Some (mkConf G3 (bl :: L) (hd bl R) (tl R)).
Proof. reflexivity. Qed.

Lemma st_G3_on : forall L R,
  step tbl (mkConf G3 L on R) = Some (mkConf WALK (on :: L) (hd bl R) (tl R)).
Proof. reflexivity. Qed.

(** ** Blocks and halves *)

Lemma zeros_succ : forall n L, zeros n ++ bl :: L = zeros (S n) ++ L.
Proof.
  intros n. induction n as [|n IH]; intros L.
  - reflexivity.
  - simpl. rewrite IH. reflexivity.
Qed.

Lemma ones_succ : forall n L, ones n ++ on :: L = ones (S n) ++ L.
Proof.
  intros n. induction n as [|n IH]; intros L.
  - reflexivity.
  - simpl. rewrite IH. reflexivity.
Qed.

Lemma hd_zeros : forall b, hd bl (zeros b) = bl.
Proof. intros b. destruct b; reflexivity. Qed.

Lemma hd_ones : forall a L, hd bl (ones (S a) ++ L) = on.
Proof. intros a L. reflexivity. Qed.

Lemma tl_ones : forall a L, tl (ones (S a) ++ L) = ones a ++ L.
Proof. intros a L. reflexivity. Qed.

(** ** Crossing the gap *)

(** Left over [m] blanks, then the mark is erased and the head steps past it.
    The state after the erase is [G2], which reads the next cell left: a mark
    means there is another rung, a blank means the budget is spent. *)

Lemma walk_G1_left : forall m A R,
  run tbl (m + 2) (mkConf G1 (zeros m ++ on :: A) bl R) =
  Some (mkConf G2 (tl A) (hd bl A) (bl :: zeros (m + 1) ++ R)).
Proof.
  intros m. induction m as [|m IH]; intros A R.
  - cbn [Nat.add]. cbn. reflexivity.
  - replace (S m + 2) with (S (m + 2)) by lia.
    rewrite run_S. cbn [zeros]. rewrite st_G1_bl. cbn.
    rewrite IH. rewrite zeros_succ. reflexivity.
Qed.

(** Right over [m] blanks, then the wall is written and the head steps into the
    copy at [WALK]. *)

Lemma walk_G3_right : forall m A Y,
  run tbl (m + 2) (mkConf G3 A bl (zeros m ++ on :: Y)) =
  Some (mkConf WALK (on :: zeros (m + 1) ++ A) (hd bl Y) (tl Y)).
Proof.
  intros m. induction m as [|m IH]; intros A Y.
  - cbn [Nat.add]. cbn. reflexivity.
  - replace (S m + 2) with (S (m + 2)) by lia.
    rewrite run_S. cbn [zeros]. rewrite st_G3_bl. cbn.
    rewrite IH. rewrite zeros_succ. reflexivity.
Qed.

(** ** The rung branch: no budget left, so the machine halts *)

(** One mark in the budget: the walk erases it, [G2] reads the blank to its
    left, and there is no row for that, so the machine stops.  The value region
    is the literal list in the conclusion, unread and unwritten. *)

Theorem rung_halts : forall m b v,
  run tbl (m + 3)
    (mkConf ENTRY (zeros (S m) ++ on :: zeros b) on
            (zeros 2 ++ ones v ++ bl :: on :: [])) =
  Some (mkConf G2 (tl (zeros b)) bl
          (bl :: zeros (m + 1) ++ on :: zeros 2 ++ ones v ++ bl :: on :: [])).
Proof.
  intros m b v.
  set (V := zeros 2 ++ ones v ++ bl :: on :: []).
  set (E := mkConf ENTRY (zeros (S m) ++ on :: zeros b) on V).
  set (C1 := mkConf G1 (zeros m ++ on :: zeros b) bl (on :: V)).
  set (C2 := mkConf G2 (tl (zeros b)) (hd bl (zeros b))
                 (bl :: zeros (m + 1) ++ on :: V)).
  assert (H1 : run tbl 1 E = Some C1)
    by (subst E C1; rewrite run_S; cbn [zeros]; rewrite st_ENTRY_on; cbn; reflexivity).
  assert (H2 : run tbl (m + 2) C1 = Some C2)
    by (subst C1 C2; apply walk_G1_left).
  pose proof (run_cat 1 (m + 2) E C1 C2 H1 H2) as H.
  subst C2.
  rewrite hd_zeros in H.
  replace (1 + (m + 2)) with (m + 3) in H by lia.
  subst V E. exact H.
Qed.

(** The stopping configuration is a halt in the sense of the semantics, and the
    run from it is empty. *)

Theorem rung_halt_conf : forall m b v,
  halted tbl
    (mkConf G2 (tl (zeros b)) bl
            (bl :: zeros (m + 1) ++ on :: zeros 2 ++ ones v ++ bl :: on :: [])).
Proof. intros m b v. cbn. reflexivity. Qed.

Theorem rung_halts_run : forall m b v,
  run tbl (m + 4)
    (mkConf ENTRY (zeros (S m) ++ on :: zeros b) on
            (zeros 2 ++ ones v ++ bl :: on :: [])) = None.
Proof.
  intros m b v.
  replace (m + 4) with (m + 3 + 1) by lia.
  rewrite run_add, rung_halts.
  cbn [run]. rewrite st_G2_bl. reflexivity.
Qed.

(** ** The rung branch: a mark is spent and the copy is reached *)

(** At least two marks in the budget: one is erased, [G2] read the mark to its
    left, and the machine walks back over the gap to the wall, writing it, and
    stops one cell right of it in [WALK].  What the copy gets is
    [ones v ++ bl :: on :: []] intact on the right and a blank block region on
    the left, which is its own entry condition. *)

Theorem rung_reaches_copy : forall m a b v,
  run tbl (2 * m + 7)
    (mkConf ENTRY (zeros (S m) ++ ones (S (S a)) ++ zeros b) on
            (zeros 2 ++ ones v ++ bl :: on :: [])) =
  Some (mkConf WALK
          (on :: zeros (m + 2) ++ on :: ones a ++ zeros b) bl
          (zeros 1 ++ ones v ++ bl :: on :: [])).
Proof.
  intros m a b v.
  set (V := zeros 2 ++ ones v ++ bl :: on :: []).
  set (A := ones (S a) ++ zeros b).
  set (E := mkConf ENTRY (zeros (S m) ++ ones (S (S a)) ++ zeros b) on V).
  set (C1 := mkConf G1 (zeros m ++ ones (S (S a)) ++ zeros b) bl (on :: V)).
  set (C2 := mkConf G2 (tl A) (hd bl A) (bl :: zeros (m + 1) ++ on :: V)).
  set (C3 := mkConf G3 (on :: ones a ++ zeros b) bl (zeros (m + 1) ++ on :: V)).
  set (C4 := mkConf WALK (on :: zeros (m + 2) ++ on :: ones a ++ zeros b)
                 (hd bl V) (tl V)).
  assert (H1 : run tbl 1 E = Some C1).
  { subst E C1. rewrite run_S. cbn [zeros]. rewrite st_ENTRY_on.
    cbn [hd tl]. reflexivity. }
  assert (H2 : run tbl (m + 2) C1 = Some C2).
  { subst C1 C2 A. cbn [ones]. apply walk_G1_left. }
  assert (H3 : run tbl 1 C2 = Some C3).
  { subst C2 C3 A. rewrite run_S. cbn [ones tl hd]. rewrite st_G2_on.
    cbn [hd tl]. reflexivity. }
  assert (H4 : run tbl (m + 1 + 2) C3 = Some C4).
  { subst C3 C4 V. replace (m + 2) with (m + 1 + 1) by lia.
    apply walk_G3_right. }
  pose proof (run_cat 1 (m + 2) E C1 C2 H1 H2) as Ha.
  pose proof (run_cat (1 + (m + 2)) 1 E C2 C3 Ha H3) as Hb.
  pose proof (run_cat (1 + (m + 2) + 1) (m + 1 + 2) E C3 C4 Hb H4) as Hc.
  subst C4 V E.
  replace (1 + (m + 2) + 1 + (m + 1 + 2)) with (2 * m + 7) in Hc by lia.
  exact Hc.
Qed.

(** ** The value is intact *)

(** The marks right of the wall are the value's and the seed; the rung branch
    reads none of them and writes none of them, so the count is [S v] both
    before and after. *)

Theorem value_marks_before : forall v, nblk (zeros 2 ++ ones v ++ bl :: on :: []) = S v.
Proof.
  intros v.
  rewrite nblk_app, nblk_app, nblk_zeros, nblk_ones.
  cbn [nblk]. lia.
Qed.

(** ** The stage branch's decision: the block is spent

    eps_0's rounds are one block mark per round; when the block runs out, the
    decision is local.  [S1] erases a mark and tests the cell left of it, [S2]
    tests the cell right of the mark [S1] erased.  On a blank both hand over to
    [ENTRY] -- that is the recursion decision: the block is empty, so a rung is
    spent.  On a mark [S2] goes to [S3], which is another round of the stage.

    These are rows of the table, so they are one-step facts; what makes them
    worth stating is that the frame [ENTRY] is entered with is exactly the frame
    the rung branch was proved for, so the two compose. *)

Definition F0 : nat := 12.       (* a round starts: lay the block from the value *)
Definition S0 : nat := 21.       (* find the block's left end *)
Definition S1 : nat := 22.       (* erase its leftmost mark *)
Definition S2 : nat := 23.       (* is a mark left to the right? *)
Definition S3 : nat := 24.       (* yes: walk to the round's entry *)
Definition S4 : nat := 25.       (* into a round *)

Lemma st_S1_on : forall L R,
  step tbl (mkConf S1 L on R) = Some (mkConf S2 (bl :: L) (hd bl R) (tl R)).
Proof. reflexivity. Qed.

Lemma st_S1_bl : forall L R,
  step tbl (mkConf S1 L bl R) = Some (mkConf ENTRY (bl :: L) (hd bl R) (tl R)).
Proof. reflexivity. Qed.

Lemma st_S2_on : forall L R,
  step tbl (mkConf S2 L on R) = Some (mkConf S3 (on :: L) (hd bl R) (tl R)).
Proof. reflexivity. Qed.

Lemma st_S2_bl : forall L R,
  step tbl (mkConf S2 L bl R) = Some (mkConf ENTRY (bl :: L) (hd bl R) (tl R)).
Proof. reflexivity. Qed.

Lemma st_S4_on : forall L R,
  step tbl (mkConf S4 L on R) = Some (mkConf F0 (on :: L) (hd bl R) (tl R)).
Proof. reflexivity. Qed.

(** ** The decision composes with the rung branch

    The block is spent, so the machine hands over to [ENTRY] and spends a rung:
    one blank is written (the cell [S2] was on was already blank, so no mark
    changes), the wall is read, and the walk over the gap erases the budget's
    rightmost mark.  The result is [WALK], the copy's entry, in the same frame
    [rung_reaches_copy] produces -- the gap one cell wider, because [S2]'s
    blank joins it on the way out. *)

Theorem block_spent_reaches_copy : forall M a b v,
  run tbl (2 * M + 10)
    (mkConf S2 (zeros (S M) ++ ones (S (S a)) ++ zeros b) bl
            (on :: zeros 2 ++ ones v ++ bl :: on :: [])) =
  Some (mkConf WALK (on :: zeros (M + 3) ++ on :: ones a ++ zeros b) bl
          (zeros 1 ++ ones v ++ bl :: on :: [])).
Proof.
  intros M a b v.
  set (V := zeros 2 ++ ones v ++ bl :: on :: []).
  set (Z := zeros (S M) ++ ones (S (S a)) ++ zeros b).
  set (C := mkConf ENTRY (bl :: Z) on V).
  assert (H1 : run tbl 1 (mkConf S2 Z bl (on :: V)) = Some C).
  { subst C Z V. rewrite run_S. rewrite st_S2_bl. cbn. reflexivity. }
  assert (H2 : run tbl (2 * S M + 7) C =
               Some (mkConf WALK (on :: zeros (S M + 2) ++ on :: ones a ++ zeros b) bl
                       (zeros 1 ++ ones v ++ bl :: on :: []))).
  { subst C Z V. apply rung_reaches_copy. }
  pose proof (run_cat 1 (2 * S M + 7) (mkConf S2 Z bl (on :: V)) C _ H1 H2) as H.
  replace (1 + (2 * S M + 7)) with (2 * M + 10) in H by lia.
  replace (S M + 2) with (M + 3) in H by lia.
  exact H.
Qed.

