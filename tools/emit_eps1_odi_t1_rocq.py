"""Emit the Rocq finite-trace certificate for the 61-state tier-1 table.

The emitted file proves the exact 214-step run from the encoded tier-1 start
to the rest where the machine has no row, then the 215th step dies.  The first
eight rest configurations are taken from the eps1_chain model, so the file
checks model-equal landings, not merely a replay of the generated table.

Run: python tools/emit_eps1_odi_t1_rocq.py
Then: cd rocq && coqc Eps1OdiT1.v
"""

import sys
from pathlib import Path

sys.path.insert(0, 'tools')

import eps1_odi as O
import eps1_odi_t1 as T1
from eps1_super_local import chain_of, D

OUT = Path('rocq/Eps1OdiT1.v')


def _ones(cells):
    return sorted(k for k, v in cells.items() if v)


def _z(n):
    return str(n)


def _list_z(xs):
    if not xs:
        return '[]'
    return '[' + '; '.join(_z(x) for x in xs) + ']'


def build_case():
    T = T1.build_table()
    mp, mc = chain_of(D.tower(1))
    cells, head = O.mk_tape(mp, list(mc))
    init_ones = _ones(cells)

    boundaries = []
    cumulative = 0
    for k in range(1, 10):
        kind, steps, next_cells, next_head = O.campaign(cells, head, T)
        if kind != 'rest':
            raise AssertionError(f'campaign {k} ended as {kind}')
        p2, c2, _, _ = O.C.step(mp, list(mc), 1)
        expected_cells, expected_head = O.mk_tape(p2, list(c2))
        got_ones, want_ones = _ones(next_cells), _ones(expected_cells)
        if got_ones != want_ones:
            raise AssertionError(
                f'campaign {k}: tape mismatch {got_ones} != {want_ones}')
        if k < 9:
            if next_head != expected_head:
                raise AssertionError(
                    f'campaign {k}: head {next_head} != {expected_head}')
        else:
            # On the final blank tape the head is not part of the decoded
            # configuration; keep the machine's actual rest head.
            if got_ones:
                raise AssertionError('final campaign did not clear the tape')
        cumulative += steps
        boundaries.append((cumulative, next_head, got_ones))
        cells, head = next_cells, next_head
        mp, mc = p2, list(c2)

    if mc:
        raise AssertionError('model chain did not empty after nine campaigns')
    if cumulative != 214:
        raise AssertionError(f'unexpected tier-1 step total {cumulative}')
    if T.get('IN', {}).get(cells.get(head, 0)) is not None:
        raise AssertionError('the 215th step should be a missing-row death')
    return T, (head, init_ones), boundaries


def emit(T, init, boundaries):
    names = sorted(T)
    qname = {s: 'Q_' + s for s in names}
    lines = []
    lines.append('(* Generated by tools/emit_eps1_odi_t1_rocq.py. *)')
    lines.append('(* Finite-trace certificate for the 61-state tier-1 specialization. *)')
    lines.append('(* Scope: the exact tier-1 run only; not a general FGH machine. *)')
    lines.append('')
    lines.append('From Stdlib Require Import List ZArith Arith Lia Bool.')
    lines.append('Import ListNotations.')
    lines.append('Open Scope Z_scope.')
    lines.append('')
    lines.append('Inductive bit : Type := B0 | B1.')
    lines.append('Inductive dir : Type := L | R.')
    lines.append('')
    lines.append('Inductive state : Type :=')
    for i in range(0, len(names), 8):
        chunk = names[i:i + 8]
        row = '  | ' + ' | '.join(qname[s] for s in chunk)
        lines.append(row + (' .' if i + 8 >= len(names) else ''))
    lines.append('')
    lines.append('Inductive next_state : Type := St : state -> next_state | Halt.')
    lines.append('')
    lines.append('Definition trans (q : state) (b : bit) : option (bit * dir * next_state) :=')
    lines.append('  match q, b with')
    for s in names:
        for sym in (0, 1):
            r = T[s].get(sym)
            if r is None:
                continue
            w, d, nx = r
            if nx not in qname:
                raise AssertionError(f'{s}[{sym}] target {nx} missing')
            bits = 'B1' if w else 'B0'
            direction = 'R' if d == 'R' else 'L'
            lines.append(
                f'  | {qname[s]}, {"B1" if sym else "B0"} => '
                f'Some ({bits}, {direction}, St {qname[nx]})')
    lines.append('  | _, _ => None')
    lines.append('  end.')
    lines.append('')
    lines.append('(* Sparse tape: the sorted positions of the 1 cells. *)')
    lines.append('Fixpoint tape_read (t : list Z) (p : Z) : bit :=')
    lines.append('  match t with')
    lines.append('  | [] => B0')
    lines.append('  | x :: xs =>')
    lines.append('      if Z.eqb p x then B1')
    lines.append('      else if Z.ltb p x then B0')
    lines.append('      else tape_read xs p')
    lines.append('  end.')
    lines.append('')
    lines.append('Fixpoint tape_set1 (t : list Z) (p : Z) : list Z :=')
    lines.append('  match t with')
    lines.append('  | [] => [p]')
    lines.append('  | x :: xs =>')
    lines.append('      if Z.eqb p x then t')
    lines.append('      else if Z.ltb p x then p :: t')
    lines.append('      else x :: tape_set1 xs p')
    lines.append('  end.')
    lines.append('')
    lines.append('Fixpoint tape_set0 (t : list Z) (p : Z) : list Z :=')
    lines.append('  match t with')
    lines.append('  | [] => []')
    lines.append('  | x :: xs =>')
    lines.append('      if Z.eqb p x then xs')
    lines.append('      else if Z.ltb p x then t')
    lines.append('      else x :: tape_set0 xs p')
    lines.append('  end.')
    lines.append('')
    lines.append('Definition tape_write (t : list Z) (p : Z) (b : bit) : list Z :=')
    lines.append('  match b with B0 => tape_set0 t p | B1 => tape_set1 t p end.')
    lines.append('')
    lines.append('Definition move_head (p : Z) (d : dir) : Z :=')
    lines.append('  match d with L => p - 1 | R => p + 1 end.')
    lines.append('')
    lines.append('Record config : Type := mkCfg {')
    lines.append('  c_state : next_state;')
    lines.append('  c_head : Z;')
    lines.append('  c_tape : list Z')
    lines.append('}.')
    lines.append('')
    lines.append('Definition step (c : config) : option config :=')
    lines.append('  match c_state c with')
    lines.append('  | Halt => None')
    lines.append('  | St q =>')
    lines.append('      match trans q (tape_read (c_tape c) (c_head c)) with')
    lines.append('      | None => None')
    lines.append('      | Some (w, d, nq) =>')
    lines.append('          Some (mkCfg nq (move_head (c_head c) d)')
    lines.append('                        (tape_write (c_tape c) (c_head c) w))')
    lines.append('      end')
    lines.append('  end.')
    lines.append('')
    lines.append('Fixpoint step_tm (k : nat) (c : config) : option config :=')
    lines.append('  match k with')
    lines.append('  | O => Some c')
    lines.append('  | S k\' =>')
    lines.append('      match step c with')
    lines.append('      | None => None')
    lines.append('      | Some c\' => step_tm k\' c\'')
    lines.append('      end')
    lines.append('  end.')
    lines.append('')
    head, init_ones = init
    lines.append('Definition init : config :=')
    lines.append(f'  mkCfg (St Q_IN) {head} {_list_z(init_ones)}.')
    lines.append('')
    for k, (steps, h, ones) in enumerate(boundaries, 1):
        lines.append(f'Definition rest{k} : config :=')
        lines.append(f'  mkCfg (St Q_IN) {h} {_list_z(ones)}.')
        lines.append('')
    for k, (steps, h, ones) in enumerate(boundaries, 1):
        lines.append(f'Lemma rest{k}_at : step_tm {steps} init = Some rest{k}.')
        lines.append('Proof. vm_compute. reflexivity. Qed.')
        lines.append('')
    lines.append('Lemma dead_at_215 : step_tm 215 init = None.')
    lines.append('Proof. vm_compute. reflexivity. Qed.')
    lines.append('')
    lines.append('Lemma exact_run :')
    lines.append('  step_tm 214 init = Some rest9 /\\ step_tm 215 init = None.')
    lines.append('Proof. split; vm_compute; reflexivity. Qed.')
    lines.append('')
    for name in ['rest1_at', 'rest2_at', 'rest3_at', 'rest4_at', 'rest5_at',
                 'rest6_at', 'rest7_at', 'rest8_at', 'rest9_at', 'dead_at_215']:
        lines.append(f'Print Assumptions {name}.')
    lines.append('')
    return '\n'.join(lines) + '\n'


def main():
    T, init, boundaries = build_case()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(emit(T, init, boundaries), encoding='utf-8')
    print(f'wrote {OUT}: {len(T)} states, {sum(len(r) for r in T.values())} rows')
    print(f'boundaries: ' + ', '.join(
        f'{k}:{steps}' for k, (steps, _h, _o) in enumerate(boundaries, 1)))
    print('final: rest at 214, death at 215')


if __name__ == '__main__':
    main()
