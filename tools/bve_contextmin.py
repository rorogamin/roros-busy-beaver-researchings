"""Observed-context minimisation for the BVE cursor/predecessor table.

The plain Moore quotient of `bve_compose` is 44 states.  A state's rows on a
symbol it is never entered on are irrelevant, exactly as in
`eps1_contextmin.py`.  This script fires a large corpus of valid BVE tapes,
records the symbols each state actually reads, and greedily merges Y into X
when X agrees with Y on every symbol Y fires on.  Every candidate is screened
with the full `bve_compose44` check (205 flag-1, 204 flag-0, 24 raw-chain
terms); failed merges are reverted.

This is a measurement of the cursor/predecessor table only.  It does not add
the general FS arm and is not an epsilon_1 claim.

Run: python tools/bve_contextmin.py
"""

import os
import random
import sys
sys.path.insert(0, 'tools')

import eps1_bve as B
from eps1_bve import V, ZERO, ONE, phi, add
import bve_compose
import bve_compose44
import bve_two_bank as T


def term_tape(v):
    return bve_compose.term_tape(v)


def h_end(v):
    return bve_compose.h_end_of(v)


def run(TABLE, tape, head, max_steps=200_000):
    tape = dict(tape)
    state = 0
    fired = {}
    for _ in range(max_steps):
        sym = tape.get(head, 0)
        fired.setdefault(state, set()).add(sym)
        row = TABLE.get((state, sym))
        if row is None:
            return True, state, fired
        w, d, nxt = row
        tape[head] = w
        head += 1 if d == 'R' else -1
        if nxt is None:
            return True, state, fired
        state = nxt
    return False, state, fired


def corpus(n_rand=350):
    rng = random.Random(71)

    def term(d):
        if d <= 0:
            return rng.choice((ZERO, ONE))
        k = rng.randrange(4)
        if k == 0:
            return phi(0, term(d - 1))
        if k == 1:
            return phi(1, term(d - 1))
        if k == 2:
            return add(term(d - 1), term(d - 1))
        return add(phi(0, term(d - 1)), term(d - 1))

    fixed = [ONE, B.epsilon0(), B.epsilon1(), B.epsilon0_plus_one(),
             phi(0, ONE), phi(0, phi(0, ONE)),
             add(phi(0, ONE), ONE), add(ONE, ONE),
             add(phi(0, ONE), phi(0, ONE)),
             add(phi(0, ONE), phi(1, ZERO))]
    terms = list(fixed)
    while len(terms) < len(fixed) + n_rand:
        terms.append(term(3))
    out = []
    for v in terms:
        if v.is_zero():
            continue
        try:
            s = term_tape(v)
        except Exception:
            continue
        # The table contract is the H/E separator entry.
        out.append(({i: int(c) for i, c in enumerate(s)}, h_end(v)))
    return out


def contexts(TABLE, data):
    fired = {}
    for tape, head in data:
        ok, _st, f = run(TABLE, tape, head)
        if not ok:
            continue
        for s, syms in f.items():
            fired.setdefault(s, set()).update(syms)
    return fired


def exact_quotient(TABLE):
    live = bve_compose44._reachable(TABLE, 0)
    part = bve_compose44._partition(TABLE, live)
    return bve_compose44._quotient(TABLE, part)


def accepts(TABLE, n):
    old_table, old_n = bve_compose44.TABLE, bve_compose44.N_STATES
    bve_compose44.TABLE, bve_compose44.N_STATES = TABLE, n
    try:
        return bve_compose44.check()
    finally:
        bve_compose44.TABLE, bve_compose44.N_STATES = old_table, old_n


