def main():
    data = corpus()
    cur, n, _ = exact_quotient(bve_compose44.TABLE)
    print(f'start: {n} states / {len(cur)} rows, corpus={len(data)}')
    applied = []
    while True:
        fired = contexts(cur, data)
        candidate = None
        states = sorted({s for (s, _sym) in cur})
        for y in states:
            if not fired.get(y):
                continue
            for x in states:
                if x == y:
                    continue
                ok = True
                for sym in fired[y]:
                    if cur.get((y, sym)) != cur.get((x, sym)):
                        ok = False
                        break
                if ok:
                    candidate = (y, x)
                    break
            if candidate:
                break
        if candidate is None:
            break
        y, x = candidate
        trial = {}
        for (s, sym), row in cur.items():
            if s == y:
                continue
            w, d, nxt = row
            trial[(s, sym)] = (w, d, x if nxt == y else nxt)
        t2, n2, _ = exact_quotient(trial)
        if accepts(t2, n2):
            cur, n = t2, n2
            applied.append((y, x, n))
            print(f'  merge {y}->{x}: now {n} states / {len(cur)} rows')
        else:
            # Do not retry the same pair forever: block it by breaking the
            # scan over y this round.  This corpus did not validate it.
            print(f'  screen rejected {y}->{x}')
            break
    print(f'applied {len(applied)} merges; final {n} states / {len(cur)} rows')
    print('contexts:')
    ctx = contexts(cur, data)
    for s in sorted(ctx):
        print(f'  {s}: {sorted(ctx[s])}')
    print('UNDER_44:', 'yes' if n < 44 else 'no')
    path = emit_module(cur, n)
    print(f'wrote {path}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
