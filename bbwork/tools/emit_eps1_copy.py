"""Emit the eps_1 copy's table into rocq/Eps1Copy.v, and check it agrees.

Same reason as `emit_eps1_tape.py`: the tape-level proof must not be about a
retyped table.  This emits the arms of `tools/eps1_machine.py` for the states
the copy and its handover use -- the copy's own states (33..52, with the merged
`BL` gone), the handover states 60..63, and `S4` (25), which is where the
handover rejoins eps_0's stage branch.

    python tools/emit_eps1_copy.py           # rewrite the marked region
    python tools/emit_eps1_copy.py --check   # compare only, exit 1 on drift
"""

import io
import sys

sys.path.insert(0, 'tools')
import eps1_machine as m

BEGIN = '(* BEGIN TABLE -- generated by tools/emit_eps1_copy.py; do not edit *)'
END = '(* END TABLE *)'

# 33 is ENTRY, which the rung branch owns and proved in Eps1Tape.v; the copy
# starts at WALK (34) and the handover ends by jumping into S4 (25).
STATES = [s for s in range(34, 53)] + [60, 61, 62, 63, 25]


def arm(s, r, w, d, t):
    sym = 'on' if r == 1 else 'bl'
    wr = 'on' if w == 1 else 'bl'
    dr = 'true' if d == 'R' else 'false'
    tn = 'None' if t is None else str(t)
    sn = m.NAMES.get(s, str(s))
    what = 'halts' if t is None else m.NAMES.get(t, str(t))
    return '  | %d, %s => Some (%s, %s, %s)  (* %s -> %s *)' % (
        s, sym, wr, dr, tn, sn, what)


def body():
    rows = [(k, v) for k, v in sorted(m.TABLE.items()) if k[0] in STATES]
    lines = [BEGIN,
             'Definition ctbl : table := fun s b =>',
             '  match s, b with']
    lines += [arm(s, r, *v) for (s, r), v in rows]
    lines += ['  | _, _ => None',
              '  end.',
              END]
    return '\n'.join(lines)


def main(argv):
    path = 'rocq/Eps1Copy.v'
    text = io.open(path, encoding='utf-8', newline='').read()
    nl = '\r\n' if '\r\n' in text else '\n'
    flat = text.replace('\r\n', '\n')
    if BEGIN not in flat or END not in flat:
        print('markers missing in', path)
        return 1
    lo = flat.index(BEGIN)
    hi = flat.index(END, lo) + len(END)
    new = flat[:lo] + body() + flat[hi:]
    if '--check' in argv:
        ok = new == flat
        print('table in %s matches tools/eps1_machine.py: %s' % (path, ok))
        return 0 if ok else 1
    with io.open(path, 'w', encoding='utf-8', newline='') as f:
        f.write(new.replace('\n', nl))
    print('wrote %s (%d rows)' % (path, len(STATES)))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
