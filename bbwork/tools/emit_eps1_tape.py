"""Emit the eps_1 machine's table into rocq/Eps1Tape.v, and check it agrees.

The Rocq development must not carry a hand-typed copy of the Python table: a
100-row table retyped by hand is exactly the kind of thing that silently stops
being the machine.  So the arms are generated here from
`tools/eps1_machine.py` between the two markers in the .v file, and
`--check` re-generates and compares without writing.

    python tools/emit_eps1_tape.py           # rewrite the marked region
    python tools/emit_eps1_tape.py --check   # compare only, exit 1 on drift

Rocq types: `sym` is `bl | on`, `dirn` is `bool` with `true` = right, and a
state with no row for a symbol halts.
"""

import io
import os
import re
import sys

sys.path.insert(0, 'tools')
import eps1_machine as m

BEGIN = '(* BEGIN TABLE -- generated by tools/emit_eps1_tape.py; do not edit *)'
END = '(* END TABLE *)'


def arm(s, r, w, d, t):
    sym = 'on' if r == 1 else 'bl'
    wr = 'on' if w == 1 else 'bl'
    dr = 'true' if d == 'R' else 'false'
    tn = 'None' if t is None else str(t)
    sn = m.NAMES.get(s, str(s))
    what = 'halts' if t is None else m.NAMES.get(t, str(t))
    return '  | %d, %s => Some (%s, %s, %s)  (* %s -> %s *)' % (s, sym, wr, dr, tn, sn, what)


def body():
    rows = sorted(m.TABLE.items())
    lines = [BEGIN,
             'Definition tbl : table := fun s b =>',
             '  match s, b with']
    lines += [arm(s, r, *v) for (s, r), v in rows]
    lines += ['  | _, _ => None',
              '  end.',
              END]
    return '\n'.join(lines)


def main(argv):
    path = 'rocq/Eps1Tape.v'
    text = io.open(path, encoding='utf-8', newline='').read()
    nl = '\r\n' if '\r\n' in text else '\n'
    flat = text.replace('\r\n', '\n')
    if BEGIN not in flat or END not in flat:
        print('markers missing in', path)
        return 1
    lo = flat.index(BEGIN)
    hi = flat.index(END, lo) + len(END)
    new = flat[:lo] + body() + flat[hi:]
    if '--check' in argv:
        ok = new == flat
        print('table in %s matches tools/eps1_machine.py: %s' % (path, ok))
        return 0 if ok else 1
    io.open(path, 'w', encoding='utf-8', newline='').write(new.replace('\n', nl))
    print('wrote %d arms into %s' % (len(m.TABLE), path))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
